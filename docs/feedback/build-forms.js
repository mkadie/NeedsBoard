#!/usr/bin/env node
// Generate form-<variant>.md from questions.json.
// Usage:  node docs/feedback/build-forms.js
//
// Edit questions.json, then rerun this. The form-*.md files are GENERATED —
// do not hand-edit them. To add a question to every form, add its id to
// `alwaysInclude`. To add a shared body question, define it in `questions` and
// reference its id in each variant's `order`.

const fs = require('fs')
const path = require('path')

const dir = __dirname
const reg = JSON.parse(fs.readFileSync(path.join(dir, 'questions.json'), 'utf8'))

function renderQuestion(n, q, optionOverride) {
  const opts = optionOverride || q.options
  let out = `${n}. **${q.text}** *(${q.category})*\n`
  if (q.type === 'single' || q.type === 'multi') {
    for (const o of opts || []) out += `   - ${o}\n`
  } else if (q.type === 'contact') {
    for (const o of opts || []) out += `   - [ ] ${o}\n`
    out += `   - Email (only if you checked a box above): ____\n`
  }
  if (q.help) {
    for (const line of q.help.split('\n')) out += line.length ? `   > ${line}\n` : `   >\n`
  }
  return out
}

function buildVariant(id, v) {
  const ids = [...v.order]
  for (const a of reg.alwaysInclude || []) if (!ids.includes(a)) ids.push(a)

  let md = `# Feedback Form — ${v.title}${v.status ? '  · ' + v.status : ''}\n\n`
  md += `Variant id: \`${id}\`. **Generated from [\`questions.json\`](./questions.json) by \`build-forms.js\` — do not edit this file by hand.** Edit the registry and rerun \`node docs/feedback/build-forms.js\`.\n\n`
  if (v.statusBanner) md += `> ${v.statusBanner}\n\n`
  if (v.preamble) md += v.preamble + '\n\n'
  md += `## Intro text\n\n> ${reg.intro}\n`
  if (v.docUrl) md += `>\n> 📄 [${reg.docLinkLabel || 'Read about this device'}](${v.docUrl})\n`
  md += `\n## Questions\n\n`

  let n = 1
  for (const qid of ids) {
    const q = reg.questions[qid]
    if (!q) {
      console.error(`  ! unknown question id "${qid}" in variant "${id}"`)
      continue
    }
    md += renderQuestion(n++, q, v.optionOverrides && v.optionOverrides[qid])
    md += '\n'
  }
  return md.trimEnd() + '\n'
}

let count = 0
for (const [id, v] of Object.entries(reg.variants)) {
  const file = path.join(dir, `form-${id}.md`)
  fs.writeFileSync(file, buildVariant(id, v))
  console.log(`wrote ${path.relative(process.cwd(), file)}`)
  count++
}
console.log(`Done — ${count} form(s) generated.`)
